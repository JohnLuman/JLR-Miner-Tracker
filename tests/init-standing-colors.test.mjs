import assert from 'node:assert/strict';
import fs from 'node:fs';
import {initStandingClass,initSovClass,INIT_ALLIANCE_ID} from '../lib/init-standings.mjs';

const standings=new Map([[101,10],[102,5],[103,-10],[104,-5],[105,0],[501,10],[502,-10],[601,5]]);
assert.equal(initStandingClass({allianceId:INIT_ALLIANCE_ID}), 'friendly','INIT always green');
assert.equal(initStandingClass({allianceId:101},standings),'friendly','INIT blue +10');
assert.equal(initStandingClass({allianceId:102},standings),'friendly','INIT ally +5');
assert.equal(initStandingClass({allianceId:103},standings),'hostile','INIT red -10');
assert.equal(initStandingClass({allianceId:104},standings),'hostile','INIT red -5');
assert.equal(initStandingClass({allianceId:105},standings),'neutral','INIT explicit zero is neutral');
assert.equal(initStandingClass({allianceId:106},standings),'neutral','unlisted is neutral with verified contacts');
assert.equal(initStandingClass({allianceId:106},null),'unknown','missing alliance access is unverified, never neutral');
assert.equal(initStandingClass({corporationId:501,allianceId:103},standings),'friendly','specific corp contact overrides alliance');
assert.equal(initStandingClass({characterId:502,corporationId:501,allianceId:101},standings),'hostile','character contact overrides corp');
assert.equal(initSovClass(null,standings),'unclaimed','unclaimed sov cannot be labeled neutral');
assert.equal(initSovClass(INIT_ALLIANCE_ID,null),'friendly','INIT sov is green even when contact API unavailable');
assert.equal(initSovClass(103,standings),'hostile');

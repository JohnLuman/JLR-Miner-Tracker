import assert from 'node:assert/strict';
import fs from 'node:fs';
import {freshLedgerInterval,freshConfirmedScan,FIELD_SCAN_FRESH_MS} from '../lib/field-ledger-freshness.mjs';
import {addVerifiedSiteMining,autoClearFieldAtCap} from '../lib/field-auto-clear.mjs';

const t0='2026-10-17T10:00:00.000Z';
const t1='2026-10-17T10:15:00.000Z';
assert.ok(freshLedgerInterval(t0,t1),'ordered 15-min poll supports observed delta');
assert.ok(!freshLedgerInterval(t0,'2026-10-17T12:00:00Z'),'multi-hour old ledger baseline cannot prove current mining');
assert.ok(!freshLedgerInterval(t1,t0),'out-of-order poll not acceptable');
assert.ok(!freshLedgerInterval(t0,t0),'identical sample does not count twice');
assert.ok(!freshLedgerInterval('2026-10-16T23:59:00Z','2026-10-17T00:01:00Z'),'UTC day rollover always resets baseline');
assert.ok(!freshLedgerInterval(t0,t1,{afterAt:'2026-10-17T10:01:00Z'}),'scan between two polls forbids allocating older mining to new deposit');
assert.ok(freshLedgerInterval(t0,t1,{afterAt:'2026-10-17T10:00:00Z'}),'delta entirely after scan can be observed');
const scan={source:'probe-scan',lastScanAt:t0,t3:{ore:'Kylixium',detected:true}};
assert.ok(freshConfirmedScan(scan,Date.parse(t0)+FIELD_SCAN_FRESH_MS-1));
assert.ok(!freshConfirmedScan(scan,Date.parse(t0)+FIELD_SCAN_FRESH_MS),'old site evidence goes stale at 12 hours');
assert.ok(!freshConfirmedScan({...scan,source:'operator-soft-reset'},Date.parse(t1)),'assumed presence is not a genuine scan');
assert.ok(!freshConfirmedScan({...scan,t3:{detected:false}},Date.parse(t1)),'scan without deposit cannot verify progress');
assert.ok(!freshConfirmedScan(scan,Date.parse(t0)-1),'future-dated scans are invalid');
const inf={baselineAt:t0,baselineDetected:true,verifiedFromScanAt:t0,verifiedM3SinceScan:0};
assert.ok(addVerifiedSiteMining(inf,1000000,t0,t1));
assert.equal(inf.verifiedM3SinceScan,1000000);
assert.equal(addVerifiedSiteMining(inf,5000000,t1,'2026-10-17T12:01:00Z'),false,'stale poll cannot inflate mined estimate');
assert.equal(inf.verifiedM3SinceScan,1000000);
assert.equal(addVerifiedSiteMining(inf,13000000,'2026-10-17T21:59:00Z','2026-10-17T22:00:00Z'),false,'stale site scan cannot inflate verified progress');
assert.equal(autoClearFieldAtCap({status:'picked'},inf,13000000,'2026-10-17T22:00:00Z',36000000),false,'old data cannot force RED');
const server=fs.readFileSync(new URL('../server.mjs',import.meta.url),'utf8');
const app=fs.readFileSync(new URL('../public/app.js',import.meta.url),'utf8');
const status=fs.readFileSync(new URL('../public/field-status.js',import.meta.url),'utf8');
assert.doesNotMatch(server,/function reconcileFieldCardsFromLedgerCache/,'no seeding present field from entire UTC day');
assert.doesNotMatch(server,/reconciledFields=reconcileFieldCardsFromLedgerCache/,'no historical replay on the mining sync path');
assert.match(server,/if\(!freshLedgerInterval\(previousSampleAt,sampleAt\)\)/,'stale, disconnected or out-of-order character sync is rebaselined');
assert.match(server,/depletionBase=verified\?/,'unverified field m³ cannot generate percent depletion');
assert.match(server,/freshConfirmedScan\(state\.scans\?\.\[system\],Date\.parse\(sampleAt\)\)/,'real scanned current cycle required');
assert.match(server,/Never reopen a cleared field from delayed cumulative ESI alone/,'no false RED reopen from lagged mining');
assert.match(server,/const latestScan=state\.scans\?\.\[system\]/,'public metrics revalidate field scan freshness');
assert.match(app,/RECENT ESI INCREASE/,'Field cards surface only fresh samples');
assert.doesNotMatch(app,/ESI HISTORY •/,'Field cards hide stale mining estimates');
assert.match(status,/recent\(scan\.lastScanAt,now,12\)/,'field details do not show stale scan as verified');
console.log('T3 newest-evidence-only and fail-closed ESI integration tests passed.');
